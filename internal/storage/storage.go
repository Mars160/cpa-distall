// Package storage persists CLIProxyAPI hook captures for the distill plugin.
//
// One captured call is stored as three rows in three tables of one database:
//
//   - captures: the immutable summary (capture ID, host request ID, caller
//     scope, model, stream flag, timing, observed hook count). It backs the record
//     list, the filter options and the detail header. The client key plaintext is
//     never part of it.
//   - capture_bodies: the raw request, response and websocket bytes of that call,
//     opaque and never re-encoded.
//   - client_keys: key_id -> client key plaintext, one row per caller scope. The
//     summary only carries the opaque key_id; the plaintext is joined in when the
//     filter options are built, so upserting a key never rewrites a historical
//     capture.
//
// The identity of a capture is its capture_id: 128 bits generated by the plugin
// with crypto/rand at the first hook of the call and stored as a 16-byte
// BLOB/BYTEA. The host request ID is kept verbatim for support, without a
// uniqueness constraint or an index, and is never a key.
//
// A store may be sharded. With writer_count N the SQLite driver keeps N shard
// databases inside the configured data directory; a capture always lands in the
// shard its capture_id maps to (see shardIndex) and its summary and bodies are
// written there in one transaction. Reads merge the shards. The PostgreSQL driver
// keeps one database and sizes its pool for N concurrent writers. The layout of a
// SQLite data directory is described by manifest.json and is never migrated,
// rewritten or deleted: a directory that does not match the configuration is
// reported as an error.
package storage

import (
	"context"
	"database/sql"
	_ "embed"
	"errors"
	"fmt"
	"strings"
	"sync"
	"time"
)

// Driver names accepted by Open.
const (
	DriverSQLite   = "sqlite"
	DriverPostgres = "postgres"
)

// ErrClosed is returned by Store methods called after Close.
var ErrClosed = errors.New("storage: store is closed")

// ErrNotFound is returned when no capture matches the requested capture ID.
var ErrNotFound = errors.New("storage: capture not found")

// ErrSearchWindowTooDeep is returned by SearchRecords when the requested page lies
// beyond the merge window of a sharded store. Merging shards cannot push the page
// offset down into the databases (see SearchRecords), so the rows materialised for
// one page grow with the offset; the window is refused instead of being served at
// an unbounded memory cost. Callers should narrow the filters or open a record by
// capture ID, which needs no window at all.
var ErrSearchWindowTooDeep = errors.New("storage: record search window is too deep")

//go:embed schema/sqlite.sql
var sqliteSchema string

//go:embed schema/postgres.sql
var postgresSchema string

// Config selects the driver, its data source and how many writers it serves.
type Config struct {
	Driver string
	// DSN is, for the sqlite driver, the data directory holding manifest.json and
	// the shard databases (":memory:" selects a throwaway in-memory layout); for
	// postgres it is a libpq/pgx connection string.
	DSN string
	// WriterCount is the number of concurrent writers of one plugin instance. The
	// sqlite driver opens that many shard databases, the postgres driver sizes its
	// connection pool for them. 0 means DefaultWriterCount; values above
	// MaxWriterCount are rejected.
	WriterCount int
}

// Store is a concurrency-safe handle to one sharded captures store. Open owns the
// connection pools of every shard and Close releases them.
type Store struct {
	mu          sync.Mutex
	driver      string
	writerCount int
	shards      []*shard
	closed      bool
}

// shard is one physical database. Its rows adapter is the driver-specific view of
// the sqlc-generated queries; a Store with one shard behaves exactly like a
// single-database store.
type shard struct {
	index int
	db    *sql.DB
	rows  rowStore
}

// rowStore is the driver-specific adapter over the sqlc-generated queries. Every
// method is parameterised: no caller input is ever concatenated into SQL.
type rowStore interface {
	insertCapture(ctx context.Context, captureID []byte, c Capture) error
	insertCaptureBodies(ctx context.Context, captureID []byte, b CaptureBodies) error
	getCaptureBodies(ctx context.Context, captureID []byte) (CaptureBodies, error)
	upsertClientKey(ctx context.Context, keyID, clientKey string) error
	getCapture(ctx context.Context, captureID []byte) (Capture, error)
	countRecords(ctx context.Context, q recordQuery) (int64, error)
	listRecords(ctx context.Context, q recordQuery) ([]Capture, error)
	listRecordKeys(ctx context.Context) ([]keyRow, error)
	listRecordModels(ctx context.Context) ([]string, error)
	// withTx rebinds the same queries to an open transaction.
	withTx(tx *sql.Tx) rowStore
}

// keyRow is one distinct (client key ID, client key) pair. The plaintext key is
// only used to build a masked label inside this package.
type keyRow struct {
	ID  string
	Key string
}

// Open connects to the configured database, applies the embedded schema
// idempotently to every shard and verifies that the tables match this plugin
// version. An incompatible pre-existing table or data directory is reported as an
// error; it is never dropped or rewritten.
func Open(ctx context.Context, cfg Config) (*Store, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	writerCount, err := normalizeWriterCount(cfg.WriterCount)
	if err != nil {
		return nil, err
	}
	switch driver := strings.ToLower(strings.TrimSpace(cfg.Driver)); driver {
	case DriverSQLite, "sqlite3":
		return openSQLite(ctx, cfg.DSN, writerCount)
	case DriverPostgres, "postgresql", "pgx":
		return openPostgres(ctx, cfg.DSN, writerCount)
	case "":
		return nil, errors.New("storage: driver is required (sqlite or postgres)")
	default:
		return nil, fmt.Errorf("storage: unsupported driver %q (want sqlite or postgres)", cfg.Driver)
	}
}

// Driver reports the driver this store was opened with.
func (s *Store) Driver() string {
	if s == nil {
		return ""
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.driver
}

// WriterCount reports the configured number of concurrent writers. It is also the
// number of shards of a sqlite store.
func (s *Store) WriterCount() int {
	if s == nil {
		return 0
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.writerCount
}

// ShardCount reports how many physical databases back this store: writer_count for
// the sqlite driver, 1 for postgres.
func (s *Store) ShardCount() int {
	if s == nil {
		return 0
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return len(s.shards)
}

// Close releases the connection pools of every shard. It is safe to call more
// than once.
func (s *Store) Close() error {
	if s == nil {
		return nil
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return nil
	}
	s.closed = true
	shards, driver := s.shards, s.driver
	s.shards = nil
	var errs []error
	for _, sh := range shards {
		if sh == nil || sh.db == nil {
			continue
		}
		if err := sh.db.Close(); err != nil {
			errs = append(errs, fmt.Errorf("storage: close %s shard %d: %w", driver, sh.index, err))
		}
	}
	return errors.Join(errs...)
}

// active returns the immutable shard list. The slice is never mutated after Open,
// so callers may use it without holding the store lock.
func (s *Store) active() ([]*shard, error) {
	if s == nil {
		return nil, ErrClosed
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed || len(s.shards) == 0 {
		return nil, ErrClosed
	}
	return s.shards, nil
}

// closeShards releases the shards of a store that could not be opened completely.
func closeShards(shards []*shard) {
	for _, sh := range shards {
		if sh != nil && sh.db != nil {
			_ = sh.db.Close()
		}
	}
}

// timeToMicros renders a timestamp as UTC epoch microseconds, the storage format
// of the captures table. Sub-microsecond precision is dropped.
func timeToMicros(t time.Time) int64 {
	return t.UTC().UnixMicro()
}

// microsToTime is the inverse of timeToMicros; it always returns a UTC time.
func microsToTime(us int64) time.Time {
	return time.UnixMicro(us).UTC()
}

// nonNilBytes maps a nil body onto an empty non-NULL blob.
func nonNilBytes(b []byte) []byte {
	if b == nil {
		return []byte{}
	}
	return b
}

// applySchema runs the embedded schema statement by statement. The scripts only
// contain plain DDL, so a line-wise "--" comment strip plus a ";" split is enough.
func applySchema(ctx context.Context, db *sql.DB, driver, script string) error {
	for _, stmt := range splitStatements(script) {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return fmt.Errorf("storage: apply %s schema (%s): %w", driver, firstLine(stmt), err)
		}
	}
	return nil
}

// verifySchema fails loudly when an existing table does not match this plugin's
// expectations, instead of silently recreating or altering it.
func verifySchema(ctx context.Context, db *sql.DB, driver string) error {
	for _, check := range []struct {
		table   string
		selects string
	}{
		{"captures", "SELECT capture_id, request_id, client_key_id, model, requested_model, source_format, stream, started_at_us, completed_at_us, event_count FROM captures LIMIT 0"},
		{"capture_bodies", "SELECT capture_id, request_body, response_body, websocket_body FROM capture_bodies LIMIT 0"},
		{"client_keys", "SELECT key_id, client_key FROM client_keys LIMIT 0"},
	} {
		rows, err := db.QueryContext(ctx, check.selects)
		if err != nil {
			return fmt.Errorf("storage: %s %s table is incompatible with this schema; migrate it manually (existing data is never dropped automatically): %w", driver, check.table, err)
		}
		if err := rows.Close(); err != nil {
			return fmt.Errorf("storage: %s verify %s table: %w", driver, check.table, err)
		}
	}
	return nil
}

func splitStatements(script string) []string {
	var buf strings.Builder
	for _, line := range strings.Split(script, "\n") {
		if idx := strings.Index(line, "--"); idx >= 0 {
			line = line[:idx]
		}
		if strings.TrimSpace(line) == "" {
			continue
		}
		buf.WriteString(line)
		buf.WriteString("\n")
	}
	var out []string
	for _, stmt := range strings.Split(buf.String(), ";") {
		if s := strings.TrimSpace(stmt); s != "" {
			out = append(out, s)
		}
	}
	return out
}

func firstLine(stmt string) string {
	if idx := strings.IndexByte(stmt, '\n'); idx >= 0 {
		stmt = stmt[:idx]
	}
	return strings.Join(strings.Fields(stmt), " ")
}
